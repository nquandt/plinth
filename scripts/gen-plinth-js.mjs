#!/usr/bin/env node
// Generates web/plinth.js: the web host as one ES module (SPEC.md §10.3),
// for web exports (`plinth build --target web`). The sources stay plain ES
// modules in web/; this script joins them with no bundler dependency.
//
// The bundle is one function, `plinthBundle(mode, baseUrl)`. Each module
// becomes a closure in it that returns its exports, and its `import` lines
// become reads of the closures before it. In the page (`mode` "page") the
// function defines `<plinth-app>`. The app frame needs the same code: the
// element puts `plinthBundle.toString()` in the `srcdoc` of the sandboxed
// iframe and calls it there with `mode` "frame", which runs `app-frame.js`.
// So the code is in the file one time, and the frame needs no URL.
//
//   node scripts/gen-plinth-js.mjs           # write web/plinth.js
//   node scripts/gen-plinth-js.mjs --check   # fail if web/plinth.js is not up to date

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const web = path.join(root, "web");
const out = path.join(web, "plinth.js");

// In dependency order. `app-frame.js` runs only in the frame.
const MODULES = ["zip.js", "protocol.js", "ui-api.js", "plinth-web.js", "dom-renderer.js", "hub-storage.js", "frame-host.js", "plinth-app.js"];
const FRAME = "app-frame.js";

const varName = (file) => `__${file.replace(/\.js$/, "").replace(/[^a-zA-Z0-9]/g, "_")}`;

function fail(message) {
  console.error(`gen-plinth-js: ${message}`);
  process.exit(1);
}

/** The body of one module closure: imports replaced, `export` removed. */
function moduleBody(file) {
  const text = readFileSync(path.join(web, file), "utf-8").replace(/\r\n/g, "\n");
  const exports = [];
  const lines = text.split("\n").map((line) => {
    const imp = line.match(/^import\s*\{([^}]*)\}\s*from\s*"\.\/([\w.-]+)";\s*$/);
    if (imp) {
      if (!MODULES.includes(imp[2])) fail(`${file} imports ${imp[2]}, which is not in the bundle`);
      const names = imp[1]
        .split(",")
        .map((n) => n.trim())
        .filter(Boolean)
        .map((n) => n.replace(/^(\w+)\s+as\s+(\w+)$/, "$1: $2"));
      return `const { ${names.join(", ")} } = ${varName(imp[2])};`;
    }
    if (/^import\b/.test(line)) fail(`${file}: an import form that this script does not read: ${line}`);
    const exp = line.match(/^export\s+((?:async\s+)?function\*?|class|const|let)\s+(\w+)/);
    if (exp) {
      exports.push(exp[2]);
      return line.replace(/^export\s+/, "");
    }
    if (/^export\b/.test(line)) fail(`${file}: an export form that this script does not read: ${line}`);
    if (/^await\b/.test(line)) fail(`${file}: top-level await is not possible in the bundle`);
    return line;
  });
  if (/\bimport\.meta\b/.test(text)) fail(`${file} uses import.meta; the frame runs the bundle as a classic script`);
  return { body: lines.join("\n"), exports };
}

const style = readFileSync(path.join(web, "style.css"), "utf-8").replace(/\r\n/g, "\n");
const frameCss = `${style}
/* The app frame of a web export. Height "content": the frame takes the
   height of the app, so the app must not take the height of the frame. */
.pl-frame-content #app { min-height: 0; }
.pl-frame-error { padding: 24px; color: var(--pl-danger); white-space: pre-wrap; }
`;

const parts = [];
const all = [];
for (const file of MODULES) {
  const { body, exports } = moduleBody(file);
  all.push(...exports.map((name) => [name, file]));
  parts.push(`  // ---- ${file}\n  const ${varName(file)} = (() => {\n${body.trimEnd()}\n  return { ${exports.join(", ")} };\n  })();`);
}
const frame = moduleBody(FRAME);

const names = new Map();
for (const [name, file] of all) {
  if (names.has(name)) fail(`${name} is exported by ${names.get(name)} and ${file}`);
  names.set(name, file);
}
// The public API of plinth.js: the element is the main part.
const PUBLIC = ["PlinthApp", "readPlnt", "parseManifest", "loadCore", "linkApp", "Tree", "DomRenderer", "AppFrame", "hostDialog", "HubStore", "base64Bytes", "defaultCoreUrl"];
for (const n of PUBLIC) if (!names.has(n)) fail(`the public name ${n} is not exported by a module`);

const bundle = `// GENERATED by scripts/gen-plinth-js.mjs from the files in web/. Do not edit.
//
// plinth.js: the Plinth web host as one ES module (SPEC.md §10.3). Load it
// as a module script; it defines the <plinth-app> element:
//
//   <plinth-app src="app.plnt"></plinth-app>
//
// Every app runs in a sandboxed iframe whose document holds this same code.

function plinthBundle(mode, baseUrl) {
  "use strict";
  const STYLE_CSS = ${JSON.stringify(frameCss)};

${parts.join("\n\n")}

  if (mode === "frame") {
    // ---- ${FRAME}
    (() => {
${frame.body.trimEnd()}
    })();
    return null;
  }

  /** The HTML of the app frame: the style and this whole bundle, inline. */
  function frameDocument({ title, fill }) {
    const text = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
    return (
      '<!doctype html><html lang="en"><head><meta charset="utf-8">' +
      '<meta name="viewport" content="width=device-width, initial-scale=1">' +
      "<title>" + text(title) + "</title><style>" + STYLE_CSS + "</style></head>" +
      '<body class="' + (fill ? "pl-frame-fill" : "pl-frame-content") + '"><div id="app">Loading&hellip;</div>' +
      "<scr" + "ipt>(" + plinthBundle.toString() + ')("frame", "");</' + "script></body></html>"
    );
  }

  if (mode === "page") __plinth_app.defineElement({ frameDocument, baseUrl, styleCss: STYLE_CSS });
  return { ${PUBLIC.map((n) => `${n}: ${varName(names.get(n))}.${n}`).join(", ")} };
}

const api = plinthBundle(typeof document === "undefined" ? "module" : "page", import.meta.url);
export const { ${PUBLIC.join(", ")} } = api;
`;

// The bundle goes inline into HTML (the frame document, a single-file
// export): these texts would end or change the script element there.
for (const bad of [/<\/script/i, /<!--/, /<script/i]) {
  const hit = bundle.match(bad);
  if (hit) fail(`the bundle contains "${hit[0]}", which cannot be inline in a <script> element`);
}

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf-8").replace(/\r\n/g, "\n");
  } catch {}
  if (current !== bundle) fail("web/plinth.js is not up to date; run `node scripts/gen-plinth-js.mjs`");
  console.log("web/plinth.js is up to date");
} else {
  writeFileSync(out, bundle);
  console.log(`wrote web/plinth.js (${Math.round(bundle.length / 1024)} KiB, ${MODULES.length + 1} modules)`);
}
